package cli

import (
	"bytes"
	"fmt"
	"strings"
)

// CommandsMarkdown renders docs/commands.md from the command table and each
// command's own flag help, so the reference cannot drift from the CLI.
func CommandsMarkdown() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `mise run docs` from the CLI help. Do not edit by hand. -->\n\n")
	b.WriteString("# Command reference\n\n")
	b.WriteString("Usage: `skigard COMMAND [ARGS]`. Flags may come before or after positional arguments, and both `-flag` and `--flag` work.\n\n")
	b.WriteString("## Flags every command takes\n\n")
	b.WriteString("| Flag | Description |\n|---|---|\n")
	b.WriteString("| `--home PATH` | skigard home directory (default `$SKIGARD_HOME`, `~/.config/skigard`, or `%APPDATA%\\skigard` on Windows) |\n")
	b.WriteString("| `--json` | machine-readable output |\n\n")
	b.WriteString("## Exit codes\n\n")
	b.WriteString("| Code | Meaning |\n|---|---|\n")
	b.WriteString("| `0` | success |\n| `1` | policy, drift or findings (for example `verify` found drift, a scan blocked) |\n")
	b.WriteString("| `2` | usage error or failure |\n| `3` | cancelled |\n| `4` | scan coverage incomplete |\n\n")
	b.WriteString("## Commands\n\n")
	for _, c := range commands {
		b.WriteString("- [`" + c.name + "`](#skigard-" + c.name + "): " + c.summary + "\n")
	}
	b.WriteString("\n")
	for _, c := range commands {
		fmt.Fprintf(&b, "## skigard %s\n\n%s.\n\n", c.name, capitalise(c.summary))
		usage := "skigard " + c.name
		if c.args != "" {
			usage += " " + c.args
		}
		b.WriteString("```\n" + usage + "\n```\n\n")
		if rows := flagRows(c.name); len(rows) > 0 {
			b.WriteString("| Flag | Description |\n|---|---|\n")
			for _, r := range rows {
				b.WriteString(r + "\n")
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}

// isFlagType reports whether w is a value type name Go's flag package prints
// after a non-boolean flag (a boolean flag's usage can start with other words).
func isFlagType(w string) bool {
	switch w {
	case "string", "int", "duration", "float", "uint", "value":
		return true
	}
	return false
}

func capitalise(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// flagRows runs `skigard NAME -h` in process and turns Go's flag help into table
// rows, leaving out the flags shared by every command.
func flagRows(name string) []string {
	if name == "version" || name == "completion" {
		return nil
	}
	var out, errb bytes.Buffer
	Run([]string{name, "-h"}, &out, &errb)
	lines := strings.Split(errb.String(), "\n")
	if len(lines) == 0 || !strings.HasPrefix(lines[0], "Usage of skigard ") {
		return nil
	}
	var rows []string
	for i := 1; i < len(lines); i++ {
		l := lines[i]
		if !strings.HasPrefix(l, "  -") {
			continue
		}
		fields := strings.Fields(l)
		flagName, typ := fields[0], ""
		if len(fields) > 1 && isFlagType(fields[1]) {
			typ = " " + strings.ToUpper(fields[1])
		}
		desc := ""
		if i+1 < len(lines) {
			desc = strings.TrimSpace(lines[i+1])
		}
		if flagName == "-home" || flagName == "-json" {
			continue
		}
		rows = append(rows, fmt.Sprintf("| `%s%s` | %s |", "-"+flagName, typ, strings.ReplaceAll(desc, "|", "\\|")))
	}
	return rows
}
